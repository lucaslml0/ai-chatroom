#!/usr/bin/env python3
"""Build the Pages output directory for ai-chatroom.

Copies public/* into pages/ and generates pages/_worker.js from
src/index.js with the `export class ChatRoom` block removed (the Durable
Object class lives in the Worker `muse-chatroom`; Pages only needs the
default fetch handler and binds the DO with script_name).

No credentials, no account IDs -- safe to publish.
Usage: python3 build_pages.py
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
PAGES_DIR = os.path.join(HERE, "pages")


def build() -> str:
    if os.path.exists(PAGES_DIR):
        shutil.rmtree(PAGES_DIR)
    os.makedirs(PAGES_DIR)
    pub = os.path.join(HERE, "public")
    for name in os.listdir(pub):
        src = os.path.join(pub, name)
        if os.path.isfile(src):
            shutil.copy2(src, os.path.join(PAGES_DIR, name))
    with open(os.path.join(HERE, "src", "index.js"), encoding="utf-8") as f:
        src_text = f.read()
    start = src_text.index("export class ChatRoom {")
    end = src_text.index("// ---------------- Worker ----------------")
    worker_text = src_text[:start] + src_text[end:]
    assert "export class ChatRoom" not in worker_text
    assert "export default" in worker_text
    with open(os.path.join(PAGES_DIR, "_worker.js"), "w", encoding="utf-8") as f:
        f.write("// Generated by build_pages.py from src/index.js\n"
                "// (ChatRoom class removed: the DO lives in the Worker muse-chatroom)\n")
        f.write(worker_text)
    return f"built {PAGES_DIR}: " + ", ".join(sorted(os.listdir(PAGES_DIR)))


if __name__ == "__main__":
    print(build())
